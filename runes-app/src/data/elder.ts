export const ELDER: Rune[] = ROWS.map(([key, char, name, sounds, gloss, glyph, poem, history, magical], i) => {
  const poems: PoemStanza[] = poem ? [{ source: AS, translation: poem }] : [];
  return {
    id: `elder-${key}`,
    char,
    alphabet: 'elder',
    name,
    nameNote: NOTE,
    position: i + 1,
    aett: (Math.floor(i / 8) + 1) as 1 | 2 | 3,
    sounds,
    gloss,
    poems,
    history,
    magical,
    glyph: GLYPHS[glyph],
  };
});
